"""Generate the initial Latin face; the unmodified Inter font remains its fallback.

Tooling only: python -m pip install --target output/font-tools 'fonttools[woff]==4.68.0'
PowerShell: $env:PYTHONPATH='output/font-tools'; python scripts/subset-inter.py
The original and derivative retain src/app/fonts/LICENSE.txt (SIL OFL 1.1).
"""
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parents[1]
fonts = root / "src/app/fonts"
original = fonts / "InterVariable.woff2"
output = fonts / "InterLatin.woff2"
font = TTFont(original, recalcTimestamp=False)
options = subset.Options()
options.flavor = "woff2"
# Keep fontTools' standard shaping features (kerning, ligatures, marks, etc.).
# The site does not enable Inter's optional stylistic sets/character variants;
# retaining all of them adds unused alternate outlines and variation data.
# Tabular figures are explicitly used by counters, dates and credentials.
options.layout_features += ["tnum"]
options.name_IDs = ["*"]
options.name_legacy = True
options.name_languages = ["*"]
# Latin-1 includes Spanish accents, ñ, ü, ¿ and ¡. Preserve combining marks,
# punctuation, the euro, directional arrows and minus used by the interface.
# Extended Latin and other scripts remain covered by the original face below.
ranges = [(0, 0x00FF), (0x0300, 0x036F), (0x2000, 0x206F),
          (0x20AC, 0x20AC), (0x2190, 0x2199), (0x2212, 0x2212),
          (0xFFFD, 0xFFFD)]
unicodes = {point for first, last in ranges for point in range(first, last + 1)}
subsetter = subset.Subsetter(options=options)
subsetter.populate(unicodes=unicodes)
subsetter.subset(font)
font.save(output)
# Explicit coverage lets the browser skip this face for unsupported characters
# (including Chinese, which the original Inter also delegated to system fonts).
remaining = sorted(set(TTFont(original).getBestCmap()) - set(font.getBestCmap()))
coverage = []
for point in remaining:
    if coverage and point == coverage[-1][1] + 1:
        coverage[-1][1] = point
    else:
        coverage.append([point, point])
unicode_range = ",".join(f"U+{a:X}-{b:X}" if a != b else f"U+{a:X}" for a, b in coverage)
(fonts / "inter.ts").write_text('''// Generated by scripts/subset-inter.py. Both faces retain LICENSE.txt.
import localFont from "next/font/local";

export const inter = localFont({
  src: "./InterLatin.woff2",
  variable: "--font-inter",
  display: "swap",
  weight: "100 900",
  adjustFontFallback: false,
});

// Load original glyphs only when used; preserve multilingual input and metrics.
export const interExtended = localFont({
  src: "./InterVariable.woff2",
  variable: "--font-inter-extended",
  display: "swap",
  weight: "100 900",
  preload: false,
  declarations: [{ prop: "unicode-range", value: "''' + unicode_range + '''" }],
});
''', encoding="utf-8")
print(f"Inter Latin: {output.stat().st_size} bytes; full fallback: {original.stat().st_size} bytes")
